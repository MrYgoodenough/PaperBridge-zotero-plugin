"""Package a staged platform-specific Python engine and the current addon source."""
import hashlib
import argparse
import json
import platform
import shutil
import sys
import zipfile
from pathlib import Path
from package_inventory import collect_inventory, write_inventory
from sanitize_runtime import sanitize_runtime

# Source tree containing addon code and native runtime stages.
ROOT = Path(__file__).resolve().parents[1]
# Public repository hosting release artifacts and separately published update feeds.
REPOSITORY = "MrYgoodenough/PaperBridge-zotero-plugin"
# Fixed timestamps keep generated metadata and copied files independent of build time.
ZIP_DATE = (2026, 1, 1, 0, 0, 0)
# Use Unix ZIP attributes consistently when repackaging the same stage on another host.
ZIP_CREATE_SYSTEM = 3
# Apply the intended maximum DEFLATE compression to streamed and generated members.
ZIP_COMPRESSION_LEVEL = 9


def build_platform():
    """Return the native bundle name and its site-packages path."""
    machine = platform.machine().lower()
    if sys.platform == "darwin" and machine == "arm64":
        return "macos-arm64", "python/lib/python3.12/site-packages"
    if sys.platform == "win32" and machine in {"amd64", "x86_64"}:
        return "windows-x64", "python/Lib/site-packages"
    if sys.platform == "linux" and machine in {"amd64", "x86_64"}:
        return "linux-x64", "python/lib/python3.12/site-packages"
    raise SystemExit(f"Unsupported build platform: {sys.platform} {platform.machine()}")


def write_bytes(archive, name, contents):
    """Write project/generated bytes with fixed portable ZIP metadata."""
    info = zipfile.ZipInfo(name, ZIP_DATE)
    info.create_system = ZIP_CREATE_SYSTEM
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o100644 << 16
    archive.writestr(info, contents, compresslevel=ZIP_COMPRESSION_LEVEL)


# A different host may repackage a stage, but cannot create its native dependencies.
STAGED_SITE_PACKAGES = {
    "macos-arm64": "python/lib/python3.12/site-packages",
    "windows-x64": "python/Lib/site-packages",
    "linux-x64": "python/lib/python3.12/site-packages",
}
parser = argparse.ArgumentParser()
parser.add_argument("--python", choices=["bundled", "local"], default="bundled")
parser.add_argument("--platform", choices=STAGED_SITE_PACKAGES,
                    help="Repackage an existing stage; does not build or validate its native runtime")
parser.add_argument("--stage-dir", type=Path, help="Package a separate candidate runtime tree")
parser.add_argument("--output-dir", type=Path, help="Write candidate packages outside the existing dist directory")
parser.add_argument("--previous-inventory", type=Path, help="Optional same-platform/mode size baseline; warnings only")
options = parser.parse_args()
mode = options.python
# Runtime paths match stage_runtime.py and the addon launcher, never the packaging host.
PLATFORM = options.platform or build_platform()[0]
SITE_PACKAGES = STAGED_SITE_PACKAGES[PLATFORM]
manifest = json.loads((ROOT / "addon/manifest.json").read_text(encoding="utf-8"))
version = manifest["version"]
runtime = options.stage_dir.resolve() if options.stage_dir else ROOT / f".cache/package/{PLATFORM}"
if not (runtime / "runtime.json").exists():
    raise SystemExit("Run .venv/bin/python scripts/stage_runtime.py first")
metadata = json.loads((runtime / "runtime.json").read_text(encoding="utf-8"))
if metadata.get("platform") != PLATFORM:
    raise SystemExit("Staged runtime metadata does not match the selected package platform")
if options.platform:
    print(f"Repackaging the existing {PLATFORM} stage; native execution is not validated by this build.")
suffix = "-local-python" if mode == "local" else ""
# Only the built addon points at its native platform and Python-mode update channel.
manifest["applications"]["zotero"]["update_url"] = (
    f"https://raw.githubusercontent.com/{REPOSITORY}/master/updates/{PLATFORM}{suffix}.json"
)
output_dir = options.output_dir.resolve() if options.output_dir else ROOT / "dist"
output = output_dir / f"paperbridge-{version}-{PLATFORM}{suffix}.xpi"
output.parent.mkdir(parents=True, exist_ok=True)
# Different staged platforms can coexist; never reuse another platform's native payload.
payload = runtime.parent / f"runtime-payload-{PLATFORM}-{mode}.zip"
sanitize_runtime(runtime)
# Sanitization changes embedded source paths; keep native-build evidence tied to shipped bytes.
for package in metadata.get("packages", []):
    build = package.get("build")
    if package.get("name") != "opencv-image-only" or not isinstance(build, dict):
        continue
    extensions = list((runtime / SITE_PACKAGES / "cv2").rglob("cv2*.so"))
    if len(extensions) == 1:
        actual = hashlib.sha256(extensions[0].read_bytes()).hexdigest()
        if actual != build.get("extensionSha256"):
            build["unsanitizedExtensionSha256"] = build.get("extensionSha256")
            build["extensionSha256"] = actual
            build["pathSanitized"] = True
        # Relocation/signing can also change size even when a reused stage already has its final hash.
        actual_bytes = extensions[0].stat().st_size
        if actual_bytes != build.get("extensionBytes"):
            build["unsanitizedExtensionBytes"] = build.get("extensionBytes")
            build["extensionBytes"] = actual_bytes
            build["pathSanitized"] = True
# Always rebuild from current bytes: a source-built cv2 must not reuse a wheel-era ZIP.
payload_candidate = payload.with_suffix(".zip.tmp")
with zipfile.ZipFile(payload_candidate, "w", zipfile.ZIP_DEFLATED, compresslevel=ZIP_COMPRESSION_LEVEL) as archive:
    for path in sorted(runtime.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(runtime).as_posix()
        if relative.startswith("backend/") or relative == "runtime.json":
            continue
        # Bytecode generated by native checks is not part of the shipped runtime.
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        # Keep the original model and tokenizer, but not machine-local fonts or caches.
        if relative.startswith(".cache/") and not relative.startswith(
                (".cache/babeldoc/models/", ".cache/babeldoc/tiktoken/")):
            continue
        if mode == "local" and relative.startswith("python/") and not relative.startswith(SITE_PACKAGES + "/"):
            continue
        info = zipfile.ZipInfo(f"runtime/{PLATFORM}/" + relative, ZIP_DATE)
        info.create_system = ZIP_CREATE_SYSTEM
        info.compress_type = zipfile.ZIP_DEFLATED
        # Python 3.12's streaming API reads the entry level, not the archive default.
        info._compresslevel = ZIP_COMPRESSION_LEVEL
        info.external_attr = (path.stat().st_mode & 0o777) << 16
        with path.open("rb") as source, archive.open(info, "w", force_zip64=True) as destination:
            shutil.copyfileobj(source, destination)
payload_candidate.replace(payload)
shutil.copyfile(payload, output)
with zipfile.ZipFile(output, "a", zipfile.ZIP_DEFLATED, compresslevel=ZIP_COMPRESSION_LEVEL) as archive:
    write_bytes(archive, "LICENSE", (ROOT / "LICENSE").read_bytes())
    if (ROOT / "NOTICE.md").is_file():
        write_bytes(archive, "NOTICE.md", (ROOT / "NOTICE.md").read_bytes())
    metadata["version"] = version
    metadata["pythonMode"] = mode
    # Reused native stages can carry an old output identity; it is not an input.
    metadata.pop("buildId", None)
    with payload.open("rb") as stream:
        metadata["payloadSha256"] = hashlib.file_digest(stream, "sha256").hexdigest()
    identity = hashlib.sha256(json.dumps(metadata,sort_keys=True).encode())
    for path in sorted((ROOT / "backend").glob("*.py")):
        identity.update(path.read_bytes())
    metadata["buildId"] = identity.hexdigest()
    write_bytes(archive, f"runtime/{PLATFORM}/runtime.json", json.dumps(metadata, indent=2).encode("utf-8"))
    for folder, prefix in [(ROOT / "addon", ""), (ROOT / "backend", f"runtime/{PLATFORM}/backend/")]:
        for path in sorted(folder.rglob("*")):
            if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc":
                contents = path.read_bytes()
                if path == ROOT / "addon/manifest.json":
                    contents = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
                write_bytes(archive, prefix + path.relative_to(folder).as_posix(), contents)
with output.open("rb") as stream:
    digest = hashlib.file_digest(stream,"sha256").hexdigest()
# Keep the checksum for local verification only; never upload it to GitHub Releases.
output.with_suffix(".xpi.sha256").write_text(f"{digest}  {output.name}\n", encoding="utf-8", newline="\n")
# Inspect completed bytes, not the stage's estimates or unverified license names.
inventory_path = output.with_suffix(".xpi.inventory.json")
inventory = collect_inventory(output, digest, options.previous_inventory)
write_inventory(inventory_path, inventory)
# Hash the completed XPI, not the cached runtime; keep unpublished feeds out of updates/.
zotero = manifest["applications"]["zotero"]
updates = {"addons": {zotero["id"]: {"updates": [{
    "version": version,
    "update_link": f"https://github.com/{REPOSITORY}/releases/download/v{version}/{output.name}",
    "update_hash": "sha256:" + digest,
    "applications": {"zotero": {
        key: zotero[key] for key in ("strict_min_version", "strict_max_version")
    }},
}]}}}
feed_dir = output.parent / "updates"
feed_dir.mkdir(exist_ok=True)
feed_path = feed_dir / f"{PLATFORM}{suffix}.json"
feed_path.write_text(json.dumps(updates, indent=2) + "\n", encoding="utf-8", newline="\n")
print(f"{output} ({output.stat().st_size:,} bytes)")
print(f"Package inventory: {inventory_path} ({len(inventory['warnings'])} advisory warnings)")
print(f"Draft update feed: {feed_path}; publish separately only after the matching release artifact exists.")
